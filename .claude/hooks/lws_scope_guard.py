def without_heredoc_bodies(command):
    """The command line minus the text of its here-documents: that is data, not commands."""
    kept, delimiters = [], []
    for line in command.split("\n"):
        if delimiters:
            if line.strip() == delimiters[0]:
                delimiters.pop(0)
            continue
        kept.append(line)
        delimiters.extend(match.group(2) for match in HEREDOC.finditer(line))
    return "\n".join(kept)


def simple_commands(command):
    """The command line split into simple commands (lists of words)."""
    command = without_heredoc_bodies(command)
    try:
        lexer = shlex.shlex(command.replace("\n", " ; "), posix=True, punctuation_chars="".join(sorted(OPERATORS)))
        lexer.whitespace_split = True
        words = list(lexer)
    except ValueError:
        return []
    commands, current = [], []
    for word in words:
        if set(word) <= OPERATORS:
            if current:
                commands.append(current)
            current = []
        else:
            current.append(word)
    if current:
        commands.append(current)
    return commands


def lws_violation(args, own):
    """Why these `lws` arguments leave the project, or None."""
    for i, arg in enumerate(args):
        option, equals, value = arg.partition("=")
        if len(option) >= 4 and ("--project-id".startswith(option) or option.startswith("--project")):
            if not equals:
                value = args[i + 1] if i + 1 < len(args) else None
            if value is not None and value != own:
                return f"names project {value!r}"
    if args[:1] == ["project"] and len(args) > 1:
        if args[1] in FOREIGN_PROJECT_COMMANDS:
            return f"`lws project {args[1]}` registers another project"
        if args[1] in NAMED_PROJECT_COMMANDS and len(args) > 2 and not args[2].startswith("-") and args[2] != own:
            return f"names project {args[2]!r}"
    return None


def short_flags(word):
    """The letters of a short-option cluster (`-am` -> "am"), or "" for anything else."""
    return word[1:] if word.startswith("-") and not word.startswith("--") and len(word) > 1 else ""


def commit_skips_hooks(args):
    """Whether `git commit ARGS` turns the hooks off (--no-verify, or -n in a short-option cluster)."""
    skip_next = False
    for word in args:
        if skip_next:
            skip_next = False
            continue
        if word == "--":
            return False
        if word == "--no-verify":
            return True
        if word in COMMIT_VALUE_OPTIONS:
            skip_next = True
            continue
        for i, letter in enumerate(short_flags(word)):
            if letter == "n":
                return True
            if letter in COMMIT_VALUE_LETTERS:
                skip_next = i == len(word) - 2  # the value is the next word only when the letter ends the cluster
                break
    return False


class Checkout:
    """What the guard knows of the checkout a command runs in: its directory and, read lazily, the branch
    checked out there; a `git checkout` / `git switch` earlier in the same command line moves it."""

    def __init__(self, cwd):
        self.cwd = cwd or os.getcwd()
        self._branch = None
        self._read = False

    def branch(self, where=None):
        if where:
            try:
                out = subprocess.run(["git", "-C", os.path.join(self.cwd, where), "rev-parse", "--abbrev-ref", "HEAD"],
                                     capture_output=True, text=True, timeout=5)
            except (OSError, subprocess.SubprocessError):
                return None
            return out.stdout.strip() if out.returncode == 0 else None
        if not self._read:
            self._read = True
            try:
                out = subprocess.run(["git", "-C", self.cwd, "rev-parse", "--abbrev-ref", "HEAD"],
                                     capture_output=True, text=True, timeout=5)
                self._branch = out.stdout.strip() if out.returncode == 0 else None
            except (OSError, subprocess.SubprocessError):
                self._branch = None
        return self._branch

    def switched(self, branch):
        self._read, self._branch = True, branch


def push_route(rest, checkout, where):
    """'push' when the push forces or deletes a long-lived branch, else None."""
    forcing = any(w in ("-f", "--force", "--mirror") or w.startswith("--force-with-lease") or w.startswith("--force-if-includes")
                  or ("f" in short_flags(w) and not w.startswith("--")) for w in rest)
    deleting = any(w in ("-d", "--delete") for w in rest)
    words = [w for w in rest if not w.startswith("-")]
    refspecs = words[1:]  # the first word is the remote
    targets = set()
    for spec in refspecs:
        if spec.startswith("+"):
            forcing = True
            spec = spec[1:]
        if spec.startswith(":"):
            deleting = True
        targets.add(spec.rsplit(":", 1)[-1].removeprefix("refs/heads/"))
    if not refspecs and (forcing or deleting):
        targets.add(checkout.branch(where) or "")
    if "--mirror" in rest or "--all" in rest and forcing:
        return "push"
    if (forcing or deleting) and targets & set(PROTECTED):
        return "push"
    return None


def git_route(args, checkout=None):
    """The ROUTES key for `git ARGS` when it bypasses little-workshop, or None."""
    checkout = checkout or Checkout(None)
    i, overrides, where = 0, [], None
    while i < len(args) and args[i].startswith("-"):
        option = args[i].split("=", 1)[0]
        if option in GIT_VALUE_OPTIONS and "=" not in args[i]:
            if option == "-c" and i + 1 < len(args):
                overrides.append(args[i + 1])
            if option == "-C" and i + 1 < len(args):
                where = args[i + 1]
            i += 2
            continue
        i += 1
    if any(o.split("=", 1)[0].lower() == "core.hookspath" for o in overrides):
        return "hooks-path"
    if i >= len(args):
        return None
    sub, rest = args[i], args[i + 1:]
    if sub in ("checkout", "switch") and not where:
        names = [w for w in rest if not w.startswith("-")]
        creating = any(w in ("-b", "-B", "-c", "-C", "--orphan") for w in rest)
        if names and "--" not in rest and (creating or len(names) == 1):
            checkout.switched(names[0])
        return None
    if sub in ("merge", "cherry-pick"):
        if any(w in SETTLING for w in rest):
            return None
        return sub if checkout.branch(where) in PROTECTED else None
    if sub == "tag":
        return "tag"
    if sub == "push":
        return push_route(rest, checkout, where)
    if sub == "commit":
        return "no-verify" if commit_skips_hooks(rest) else None
    if sub == "branch":
        deleting = any(w in ("--delete", "-d", "-D") or set(short_flags(w)) & {"d", "D"} for w in rest)
        named = {w for w in rest if not w.startswith("-")}
        return "branch-delete" if deleting and named & set(PROTECTED) else None
    if sub == "reset":
        return "destructive" if "--hard" in rest else None
    if sub == "clean":
        return "destructive"
    if sub == "config" and any(w.lower() == "core.hookspath" for w in rest):
        values = [w for w in rest if not w.startswith("-") and w.lower() != "core.hookspath"]
        unsetting = any(w in ("--unset", "--unset-all") for w in rest)
        return "hooks-path" if unsetting or (values and values != [".githooks"]) else None
    return None


def command_route(words, checkout=None):
    """The ROUTES key for one simple command, or None."""
    base = words[0].rsplit("/", 1)[-1]
    args = words[1:]
    if base in ("git", "git.exe"):
        return git_route(args, checkout)
    if base == "systemd-run":
        return "systemd"
    if base == "systemctl" and "--user" in args and set(args) & {"start", "stop", "restart", "kill"}:
        return "systemd"
    if base == "twine":
        return "publish"
    if base == "pipx" and args[:1] == ["install"]:
        return "install"
    if base in ("gh", "gh.exe") and args[:2] == ["repo", "delete"]:
        return "repo-delete"
    if base in ("gh", "gh.exe") and (args[:2] in (["repo", "create"], ["pr", "merge"]) or args[:1] == ["release"]):
        return "github"
    return None


def without_env_assignments(words):
    """The words after any leading NAME=value assignments and `env`, `command`, `exec`, `sudo`."""
    i = 0
    while i < len(words) and (re.match(r"^[A-Za-z_]\w*=", words[i]) or words[i] in ("env", "command", "exec", "sudo")):
        i += 1
    return words[i:]


def bash_violation(command, own, checkout=None, check_lws=True):
    checkout = checkout or Checkout(None)
    for words in simple_commands(command):
        words = without_env_assignments(words)
        if not words:
            continue
        if words[0] == "cd" and len(words) > 1:
            checkout = Checkout(os.path.join(checkout.cwd, words[1]))
            continue
        route = command_route(words, checkout)
        if route:
            shown = " ".join(words[:3])
            return f"`{shown}` is refused here: {ROUTES[route]}."
        for i, word in enumerate(words):
            base = word.rsplit("/", 1)[-1]
            if base == "lws":
                problem = lws_violation(words[i + 1:], own) if check_lws else None
                if problem:
                    return (f"this checkout is project {own!r} but the lws command {problem}. Work on other "
                            "projects belongs in a session started from the little-projects root.")
                break
            if base in SHELLS:
                for j, option in enumerate(words[i + 1:], i + 1):
                    if option.startswith("-") and not option.startswith("--") and "c" in option[1:]:
                        if j + 1 < len(words):
                            problem = bash_violation(words[j + 1], own, checkout, check_lws)
                            if problem:
                                return problem
                        break
                break
    return None


def lws_command(args):
    """The command path of `lws ARGS` (`version status`), as PLATFORM_FREE_LWS lists it."""
    words = [w for w in args if not w.startswith("-")]
    for length in (3, 2):
        if " ".join(words[:length]) in PLATFORM_FREE_LWS:
            return " ".join(words[:length])
    return " ".join(words[:2])


def platform_lws(command, own):
    """In little-workshop's own session: ("allow", why) when every simple command is an lws call that only reads
    or applies little-workshop in some project, ("ask", why) when one acts on another project otherwise, else None."""
    asks, free = [], 0
    commands = [without_env_assignments(w) for w in simple_commands(command)]
    commands = [w for w in commands if w]
    for words in commands:
        if words[0].rsplit("/", 1)[-1] != "lws":
            continue
        problem = lws_violation(words[1:], own)
        path = lws_command(words[1:])
        if problem is None or path in PLATFORM_FREE_LWS:
            free += 1
        else:
            asks.append(f"`lws {path}` {problem}: a change to that project's own state, not little-workshop's")
    if asks:
        return "ask", "; ".join(asks)
    if commands and free == len(commands):
        return "allow", "reads or applies little-workshop in a project"
    return None


def checkout_of(path):
    """The git checkout holding `path` (the nearest folder with a .git), or None."""
    folder = os.path.dirname(path)
    while folder and folder != os.path.dirname(folder):
        if os.path.exists(os.path.join(folder, ".git")):
            return folder
        folder = os.path.dirname(folder)
    return None


def platform_edit(args, root):
    """In little-workshop's own session, an edit in another project's checkout: ("deny"|"ask", why) or None."""
    path = args.get("file_path") or args.get("notebook_path")
    if not isinstance(path, str) or not path or not root or not os.path.isabs(path):
        return None
    full = os.path.realpath(path)
    other = checkout_of(full)
    if other is None or os.path.realpath(other) == os.path.realpath(root):
        return None
    rel = os.path.relpath(full, other).replace(os.sep, "/")
    name = os.path.basename(other)
    if rel in GENERATED or rel in GIT_HOOKS:
        return "deny", (f"{name}/{rel} is generated by little-workshop: change the generator here and apply it with "
                        f"`python3 tools/sync_claude_files.py --checkout {other} --write` (no prompt)")
    return "ask", (f"this little-workshop session would write {name}'s own file {rel}: project work, not a "
                   f"little-workshop change (it is normally done in {name}'s session or from little-projects)")


def mcp_violation(tool, args, own):
    name = tool[len(PREFIX):]
    project = args.get("project_id")
    if project is not None and project != own:
        return f"{name} names project {project!r}"
    if project is None and name in NEEDS_PROJECT_ID:
        return f"{name} without project_id acts on every project"
    if name in NAMED_PROJECT and args.get("name") != own:
        return f"{name} names project {args.get('name')!r}"
    for entry in args.get("projects") or ():
        other = entry.get("project_id") if isinstance(entry, dict) else None
        if other is not None and other != own:
            return f"{name} names project {other!r}"
    return None


def outside_section(text):
    """The text before and after the project's own section of a generated file, or None without one."""
    start = text.find(SECTION_START)
    end = text.find(SECTION_END, start + 1) if start >= 0 else -1
    return (text[:start], text[end:]) if start >= 0 and end >= 0 else None


def edits_only_own_section(full, args):
    """Whether the edit changes nothing of a generated file but its project-owned section."""
    try:
        with open(full, encoding="utf-8") as fh:
            current = fh.read()
    except (OSError, UnicodeDecodeError):
        return False
    kept = outside_section(current)
    if kept is None:
        return False
    if isinstance(args.get("content"), str):
        return outside_section(args["content"]) == kept
    edited = current
    for edit in args.get("edits") or [args]:
        old, new = edit.get("old_string"), edit.get("new_string")
        if not isinstance(old, str) or not isinstance(new, str) or not old or old not in edited:
            return False
        edited = edited.replace(old, new) if edit.get("replace_all") else edited.replace(old, new, 1)
    return outside_section(edited) == kept


def edit_violation(args, root, own):
    """Why editing this file is refused, or None. Paths outside the checkout pass."""
    path = args.get("file_path") or args.get("notebook_path")
    if not isinstance(path, str) or not path or not root:
        return None
    full = os.path.realpath(path if os.path.isabs(path) else os.path.join(root, path))
    rel = os.path.relpath(full, os.path.realpath(root)).replace(os.sep, "/")
    if rel == ".." or rel.startswith("../"):
        return None
    if rel.rsplit("/", 1)[-1] in STRAY_INSTRUCTIONS or rel == ".claude/CLAUDE.md":
        return (f"{rel} is refused here: Claude Code reads AGENTS.md only where no CLAUDE.md, .claude/CLAUDE.md or "
                "CLAUDE.local.md exists. Write a learned rule (claude-reflect's included) as a bullet in "
                f"{LEARNED_RULES}, project guidance in .claude/AGENTS.md or a path-scoped .claude/rules/ file, and "
                "personal notes in ~/.claude/.")
    if rel in GENERATED and not edits_only_own_section(full, args):
        own_section = (f" Only the part between {SECTION_START} and {SECTION_END} is the project's to edit."
                       if rel.endswith(".md") else "")
        return f"{rel} is refused here: {GENERATED[rel]}.{own_section}"
    if rel in GIT_HOOKS:
        return (f"{rel} is refused here: `lws version install-hooks --project-id {own}` writes it (generator: "
                "little-workshop's src/version/commands/git_hooks.py).")
    return None


def decide(decision, reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": decision,
        "permissionDecisionReason": f"little-workshop: {reason}",
    }}))


def main():
    own = sys.argv[1] if len(sys.argv) > 1 else ""
    platform = "--platform" in sys.argv[2:]
    try:
        event = json.load(sys.stdin)
        tool = event["tool_name"]
        args = event.get("tool_input") or {}
    except (ValueError, KeyError, TypeError):
        return
    if not own or not isinstance(args, dict):
        return
    root = os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd")
    if platform and tool.startswith(PREFIX):
        problem = mcp_violation(tool, args, own)
        if problem and tool[len(PREFIX):] not in PLATFORM_FREE_MCP:
            decide("ask", f"{problem}: a change to that project's own state, not little-workshop's")
        return
    if platform and tool == "Bash":
        command = str(args.get("command", ""))
        verdict = platform_lws(command, own)
        problem = bash_violation(command, own, Checkout(event.get("cwd")), check_lws=False)
        if problem:
            decide("deny", problem)
        elif verdict:
            decide(*verdict)
        return
    if platform and tool in EDIT_TOOLS:
        verdict = platform_edit(args, root)
        if verdict:
            decide(*verdict)
            return
    if tool.startswith(PREFIX):
        problem = mcp_violation(tool, args, own)
        if problem:
            problem = (f"this checkout is project {own!r} but {problem}. Work on other projects belongs in a "
                       "session started from the little-projects root.")
    elif tool == "Bash":
        problem = bash_violation(str(args.get("command", "")), own, Checkout(event.get("cwd")))
    elif tool in EDIT_TOOLS:
        problem = edit_violation(args, root, own)
    else:
        return
    if problem:
        decide("deny", problem)


if __name__ == "__main__":
    main()
